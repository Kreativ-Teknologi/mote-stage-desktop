import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {makeActorAction,createActorActionPlayer,actorGesturePose,blendActorEye,blendActorMouth,ACTOR_APERTURES,libraryEmoteMotion} from '../web/actor-actions.js';
import {normalizeEmoteLayout,removeSlotPart} from '../web/emote-layout.js';
import {mapWebcamExpression} from '../web/face-mapping.js';
let time=0,wall=100000;
const comboSlot={name:'joy',key:'1',form:'star',lookId:'first',followUp:'smirk',nextForm:'triangle',nextLookId:'second'};
assert.deepEqual(normalizeEmoteLayout(JSON.parse(JSON.stringify([comboSlot])))[0],comboSlot);
assert.deepEqual(removeSlotPart(comboSlot,'emote'),{name:'smirk',key:'1',form:'triangle',lookId:'second'});
assert.deepEqual(removeSlotPart(comboSlot,'followUp'),{name:'joy',key:'1',form:'star',lookId:'first'});
const {nextLookId,...withoutSecondLook}=comboSlot;
assert.deepEqual(removeSlotPart(comboSlot,'nextLook'),withoutSecondLook);
for(const name of ['smirk','squint','disgust']){
  assert.ok(makeActorAction('expression',name,4,'blend',0,name));
  assert.ok(Object.values(libraryEmoteMotion(name,450)).some(value=>Math.abs(value)>.1));
}
for(const [name,peak] of Object.entries({deadpan:900,doubleTake:490,sigh:1410,wince:300,tender:950,stifledLaugh:480})){
  const cue=makeActorAction('expression',name,4,'blend',0,name);
  assert.equal(cue?.name,name);
  const motion=libraryEmoteMotion(name,peak);
  assert.ok(Object.values(motion).every(Number.isFinite));
  assert.ok(Object.values(motion).some(value=>Math.abs(value)>.1),name+' has a visible beat');
  assert.ok(Object.values(libraryEmoteMotion(name,0)).every(value=>value===0),name+' eases in from rest');
}
let comboTime=0;
const comboPlayer=createActorActionPlayer(()=>comboTime,()=>wall+comboTime);
const cue=makeActorAction('expression','joy',4,'blend',wall,'combo','star','smirk',{scene:'aether'},'triangle',{scene:'ember'});
comboPlayer.receive(cue);
comboTime=3999;
assert.equal(comboPlayer.visual().form,'star');
assert.equal(comboPlayer.visual().appearance.scene,'aether');
comboTime=4000;
const reconnected=createActorActionPlayer(()=>comboTime,()=>wall+comboTime);
reconnected.receive(JSON.parse(JSON.stringify(comboPlayer.current())));
for(const output of [comboPlayer,reconnected]){
  assert.equal(output.visual().name,'smirk');
  assert.equal(output.visual().form,'triangle');
  assert.equal(output.visual().appearance.scene,'ember');
  assert.equal(output.visual().formWeight,1);
}
comboTime=8000;
assert.equal(comboPlayer.visual(),null);
const inherited=makeActorAction('expression','joy',4,'blend',wall+comboTime,'inherit','star','smirk',{scene:'dawn'});
comboPlayer.receive(inherited);
comboTime=12500;
assert.equal(comboPlayer.visual().form,'star');
assert.equal(comboPlayer.visual().appearance.scene,'dawn');
const player=createActorActionPlayer(()=>time,()=>wall);
const action=(kind,name,duration=4,mode='blend',id=name)=>makeActorAction(kind,name,duration,mode,wall,id);
assert.equal(makeActorAction('expression','unknown'),null);
assert.equal(action('expression','joy',1).duration,3000);
assert.equal(action('expression','joy',20).duration,5000);
const smile=action('expression','joy');player.receive(smile);
assert.equal(player.sample().weight,0,'Actions enter smoothly');
time=500;assert.equal(player.sample().weight,.86,'Blend leaves some live expression present');
time=3200;assert.equal(player.sample().weight,.86,'Four-second action holds through its performance');
time=3700;const fading=player.sample().weight;assert.ok(fading>0&&fading<.86,'Tracking returns gradually');
player.receive(smile);assert.equal(player.sample().weight,fading,'Reconnect/duplicate cannot restart an action');
time=4000;assert.equal(player.sample(),null,'Temporary action expires independently of the render animation clock');
player.receive(smile);assert.equal(player.sample(),null,'Expired actions never replay');
time=5000;wall=105000;player.receive(action('expression','angry',3,'override'));
time=5500;assert.equal(player.sample().weight,1,'Override fully owns the expression during its hold');
player.release();time=5610;assert.ok(player.sample().weight>0&&player.sample().weight<1,'Release eases back');
time=5730;assert.equal(player.sample(),null);
const late=action('gesture','look-left',5,'override','late');wall+=700;time=6000;player.receive(late);
assert.equal(player.sample().elapsed,700,'A newly opened output resumes the remaining action time');
assert.equal(player.sample().remaining,4300);
const head=actorGesturePose({...player.sample(),weight:1},{yaw:.6});assert.ok(Math.abs(head.yaw+.6+.46)<1e-8,'Look override wins over opposing tracking');
assert.equal(actorGesturePose({kind:'gesture',name:'blink',weight:.86,mode:'blend'}).blink,1,'Close eyes reaches complete closure even in Blend mode');
player.receive(null);time+=230;assert.equal(player.sample(),null,'Remote release follows the same path');
let switchTime=0;
const transition=createActorActionPlayer(()=>switchTime,()=>100000+switchTime);
const play=name=>transition.receive(makeActorAction('expression',name,4,'blend',100000+switchTime,name));
play('orbit');
switchTime=1000;
const beforeSwitch=transition.visual();
play('explosion');
assert.equal(transition.sample().name,'explosion','Actor controls acknowledge the replacement immediately');
assert.deepEqual(transition.visual(),beforeSwitch,'Replacing a live effect preserves its current visual pose');
switchTime=1085;
assert.equal(transition.visual().weight,beforeSwitch.weight/2,'The outgoing effect fades through the handoff');
const halfway=transition.visual();
play('rainbow');
assert.deepEqual(transition.visual(),halfway,'Rapid presses continue from the visible blend, not a hidden cue');
switchTime=1255;
assert.equal(transition.visual().name,'rainbow');
assert.equal(transition.visual().weight,0,'The new effect starts at zero');
switchTime=1345;
assert.equal(transition.visual().elapsed,90,'The new cue starts from its beginning after the handoff');
assert.ok(transition.visual().weight>0&&transition.visual().weight<.86);
transition.release();
switchTime+=221;
assert.equal(transition.visual(),null,'Release clears a visual transition completely');
const tracked=mapWebcamExpression({jawOpen:.7,mouthFrownLeft:.5,mouthFrownRight:.5});
const profile=[1.12,.42,.2,.07,-.13,0,.07];
const mouth=blendActorMouth(tracked,profile,1,ACTOR_APERTURES.joy);
assert.equal(mouth.opening,tracked.opening,'Speech articulation continues beneath an expression override');
assert.equal(mouth.curve,-.13,'Smile wins over a tracked frown');
const rest=mapWebcamExpression({});assert.ok(blendActorMouth(rest,profile,.86,ACTOR_APERTURES.joy).opening>0,'An explicit Smile action remains legible on a closed resting mouth');
assert.equal(blendActorMouth(rest,profile,0,ACTOR_APERTURES.joy).opening,0,'The resting mouth closes again when the action finishes');
const before=structuredClone(tracked.eyes[0]);const eye=blendActorEye(tracked.eyes[0],profile,0,1);
assert.equal(eye.height,.42);assert.deepEqual(tracked.eyes[0],before,'Tracked coefficients are never mutated');
assert.deepEqual(blendActorEye(before,profile,0,0),before,'Release restores the exact live eye target');
console.log('Verified Actor timing, blend/override, smooth release, reconnect, head gestures, complete eye closure and preserved speech/tracking.');

