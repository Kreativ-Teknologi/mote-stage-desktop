import {createAudioFluidDriver,createVoiceEnvelope} from '../web/fluid-motion.js';
import assert from 'node:assert/strict';
import {mapWebcamExpression} from '../web/face-mapping.js';
import {createTrackingFailsafe} from '../web/tracking-failsafe.js';
const neutral=mapWebcamExpression({}),smile=mapWebcamExpression({mouthSmileLeft:.25,mouthSmileRight:.25}),frown=mapWebcamExpression({mouthFrownLeft:.25,mouthFrownRight:.25});
assert.equal(neutral.opening,0,'Resting mouth remains closed');
assert.equal(smile.opening,0,'A closed smile must not force the mouth on');
assert.ok(smile.curve<-.1&&frown.curve>.1,'Moderate face movement produces legible smile and frown');
assert.ok(smile.eyes[0].height<neutral.eyes[0].height,'Smiles reshape the white eyes');
const asymmetric=mapWebcamExpression({browOuterUpLeft:.3});assert.ok(asymmetric.eyes[0].lift>asymmetric.eyes[1].lift,'Brow asymmetry is preserved');
assert.ok(mapWebcamExpression({jawOpen:.2},2).opening>mapWebcamExpression({jawOpen:.2},.6).opening,'Expression strength changes amplification');
const f=createTrackingFailsafe();
const tick=(now,tracked,extra={})=>f.update({now,tracked,enabled:true,cameraRequested:true,...extra});
assert.equal(tick(0,false).blackout,false,'Initial setup does not shut down an unarmed character');
assert.equal(tick(10,true).blackout,false);
assert.equal(tick(700,false).blackout,false,'Short tracking gaps do not interrupt the show');
assert.equal(tick(1210,false).blackout,true,'Actor leaving triggers automatic shutdown');
assert.equal(tick(1300,true).blackout,true,'Recovery waits for stable tracking');
assert.equal(tick(1450,false).blackout,true,'A flickering detection cannot restore the image');
assert.equal(tick(1500,true).blackout,true);
assert.equal(tick(1850,true).blackout,false,'Stable reacquisition restores power');
assert.equal(tick(4000,false).blackout,true);
assert.equal(tick(4100,false,{enabled:false}).blackout,false,'Disabling the failsafe releases its own blackout');
assert.equal(tick(4200,false,{cameraRequested:false}).armed,false,'Stopping the webcam disarms the failsafe');
console.log('Verified expressive face mapping, tracking-loss grace, stable recovery, jitter resistance and disarming.');

const fluid=createAudioFluidDriver();let silent=fluid.update(0,1/60,true),loud;
for(let i=0;i<60;i++)loud=fluid.update(.8,1/60,true);
assert.ok(loud.deform>silent.deform+.3,'Vocal amplitude increases real deformation');
const frozen=fluid.update(.1,0,true);assert.equal(frozen.phase,loud.phase,'Freeze does not advance fluid motion');
let disabled;for(let i=0;i<180;i++)disabled=fluid.update(.8,1/60,false);
assert.equal(disabled.level,0,'Disabled voice motion returns to idle even while input remains loud');
assert.ok(disabled.phase>loud.phase,'Base fluid motion continues when voice modulation is disabled');

const voice=createVoiceEnvelope();let envelope=voice.update(0,1/60);
assert.equal(envelope,0);
for(let i=0;i<60;i++)envelope=voice.update(1,1/60);
assert.ok(envelope>.99,'Voice halo attacks promptly');
const held=voice.update(0,0);assert.equal(held,envelope,'Freeze holds halo energy');
const falling=voice.update(0,1/60);assert.ok(falling>0&&falling<held,'Voice halo releases without snapping');
for(let i=0;i<240;i++)envelope=voice.update(0,1/60);
assert.equal(envelope,0,'Silence clears the voice halo envelope');
